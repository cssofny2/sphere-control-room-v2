// Builds src/technician/knowledge.generated.ts from the Markdown files in src/technician/knowledge/
// plus the app's own help text (OVERVIEW_HELP, GLOSSARY, PROCEDURE_STEPS, FAULT_CATALOG), so the
// technician's facts always come from the repo. Run: node scripts/build-knowledge.mjs [--check]
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadTypeScript } from './load-typescript.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const kbDir = path.join(root, 'src/technician/knowledge');
const outFile = path.join(root, 'src/technician/knowledge.generated.ts');

const entries = [];
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

for (const file of fs.readdirSync(kbDir).filter(f => f.endsWith('.md')).sort()) {
  const src = fs.readFileSync(path.join(kbDir, file), 'utf8');
  for (const block of src.split(/^## /m).slice(1)) {
    const [head, ...rest] = block.split('\n');
    let body = rest.join('\n').trim(), keywords = [];
    const m = body.match(/^Keywords:\s*(.+)\n?/);
    if (m) { keywords = m[1].split(',').map(s => s.trim().toLowerCase()).filter(Boolean); body = body.slice(m[0].length).trim(); }
    entries.push({ id: `${file.replace('.md', '')}.${slug(head)}`, source: `knowledge/${file}`, title: head.trim(), keywords, text: body.replace(/\n+/g, ' ') });
  }
}

// Pull plain-object constants out of the app source without importing React.
const appSrc = fs.readFileSync(path.join(root, 'src/MetrologyLabV3.tsx'), 'utf8');
function grab(name, open, close) {
  const i = appSrc.indexOf(`const ${name} = ${open}`); if (i < 0) throw new Error(`Cannot find ${name} in MetrologyLabV3.tsx`);
  const start = i + `const ${name} = `.length; const end = appSrc.indexOf(`\n${close};`, start);
  return new Function(`return (${appSrc.slice(start, end + 1 + close.length)})`)();
}
const GLOSSARY = grab('GLOSSARY', '{', '}');
for (const [k, v] of Object.entries(GLOSSARY)) entries.push({ id: `glossary.${k}`, source: 'MetrologyLabV3.tsx GLOSSARY', title: v.title, keywords: [k.replace(/_/g, ' '), v.title.toLowerCase()], text: v.desc });
const PROC = grab('PROCEDURE_STEPS', '[', ']');
for (const p of PROC) entries.push({ id: `procedure.step${p.step}`, source: 'MetrologyLabV3.tsx PROCEDURE_STEPS', title: `Procedure step ${p.step}: ${p.title}`, keywords: ['procedure', 'step', String(p.step), p.title.toLowerCase()], text: p.desc });
const FAULTS = grab('FAULT_CATALOG', '{', '}');
for (const [k, v] of Object.entries(FAULTS)) entries.push({ id: `faultcatalog.${k}`, source: 'MetrologyLabV3.tsx FAULT_CATALOG', title: v.title, keywords: [k.toLowerCase(), v.title.toLowerCase()], text: `Symptoms: ${v.symptoms} Fix: ${v.fix}` });

const H = await loadTypeScript(new URL('../src/overview/overviewHelp.ts', import.meta.url));
for (const [k, v] of Object.entries(H.OVERVIEW_HELP)) entries.push({ id: k, source: 'overview/overviewHelp.ts', title: v.title, keywords: [v.title.toLowerCase(), k.replace(/^ov\./, '').replace(/_/g, ' ')], text: [v.desc, v.why && `Why it matters: ${v.why}`, v.tip && `Try: ${v.tip}`].filter(Boolean).join(' ') });

const ids = new Set(); for (const e of entries) { if (ids.has(e.id)) throw new Error(`Duplicate knowledge id ${e.id}`); ids.add(e.id); }
const out = `// GENERATED by scripts/build-knowledge.mjs — do not edit. Edit src/technician/knowledge/*.md and re-run \`npm run build:knowledge\`.\n`
  + `export type KBEntry = { id: string; source: string; title: string; keywords: string[]; text: string };\n`
  + `export const KNOWLEDGE: KBEntry[] = ${JSON.stringify(entries, null, 1)};\n`;
if (process.argv.includes('--check')) {
  const cur = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf8') : '';
  if (cur !== out) { console.error('knowledge.generated.ts is stale. Run: npm run build:knowledge'); process.exit(1); }
  console.log(`PASS knowledge base is in sync (${entries.length} entries)`);
} else { fs.writeFileSync(outFile, out); console.log(`Wrote ${entries.length} knowledge entries`); }
